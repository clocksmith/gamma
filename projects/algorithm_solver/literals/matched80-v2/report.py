"""Rebuild results.json and RESULTS.md from run-v1 artifacts. Reads only; safe to rerun."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RUN = ROOT / 'run-v1'
LIVE = {128: {'version': 'bits-literal-joint80-7-v1', 'selections': 10155, 'package_bytes': 13002},
        256: {'version': 'bits-literal-joint80-8-v1', 'selections': 6413, 'package_bytes': 11781}}


def main():
    contract = json.loads((ROOT / 'contract.json').read_text())
    arms = {}
    for folder in sorted(RUN.iterdir()):
        if folder.is_dir():
            name = folder.name
            resources = RUN / ((name.rsplit('-', 1)[0] if name.startswith('fixed') else name) + '-resources.json')
            arms[name] = {**json.loads((folder / 'manifest.json').read_text())['metrics'], 'resources': json.loads(resources.read_text())}
    sel = lambda n: arms[n]['selections']
    predictions = {
        'Q1 span-12 reproduces stored': {str(s): sel(f'fixed-span-12-{s}') == LIVE[s]['selections'] for s in LIVE},
        'Q2 wider shortlist beats span-12': {f'{w}-{s}': sel(f'fixed-span-{w}-{s}') < sel(f'fixed-span-12-{s}') for w in (48, 192) for s in LIVE},
        'Q3 hybrid <= span at same width': {f'{w}-{s}': sel(f'fixed-hybrid-{w}-{s}') <= sel(f'fixed-span-{w}-{s}') for w in (12, 48, 192) for s in LIVE},
    }
    promotion = {}
    for size, live in LIVE.items():
        best = min((n for n in arms if n.endswith(f'-{size}')), key=lambda n: (sel(n), arms[n]['package_bytes'], n))
        a = arms[best]
        promotion[str(size)] = {'live': live, 'candidate': best, 'selections': a['selections'], 'package_bytes': a['package_bytes'],
                                'selection_change': (a['selections'] - live['selections']) / live['selections'],
                                'package_change': (a['package_bytes'] - live['package_bytes']) / live['package_bytes'],
                                'meets_selection_rule': a['selections'] <= live['selections'] * 0.98,
                                'meets_package_rule': a['package_bytes'] <= live['package_bytes'] * 1.05}
    run = json.loads((RUN / 'run.json').read_text())
    results = {'schema': 'gamma.matched80.results.v2', 'run': {k: run[k] for k in ('complete', 'host', 'python', 'elapsed_seconds', 'contract_sha256')},
               'frozen_at': contract['frozen_at'], 'predictions': predictions, 'promotion': promotion, 'arms': arms}
    (ROOT / 'results.json').write_text(json.dumps(results, indent=2, sort_keys=True) + '\n')
    lines = ['# Matched 80, iteration 2 results', '', f"Generated by `report.py` (run complete: {run['complete']}, {run['elapsed_seconds']:.0f} s on {run['host']}).", '',
             '| Arm | Selections | Package B | Median / p95 | Entries (matches designed / other / fallback) | Trials | Search s |', '| --- | ---: | ---: | --- | --- | ---: | ---: |']
    for name, a in arms.items():
        p = a['entries_by_provenance']
        lines.append(f"| {name} | {a['selections']:,} | {a['package_bytes']:,} | {a['median_selections']} / {a['p95_selections']} | "
                     f"{p.get('designed', 0)} / {p.get('mined', 0)} / {p.get('fallback', 0)} | {a['resources']['trials']:,} | {a['resources']['search_seconds']:.1f} |")
    lines += ['', 'Fixed 128/256 rows share one trajectory. No arm reached its time limit.', '', '## Predictions', '']
    lines += [f"- **{k}**: " + ', '.join(f"{kk} {'holds' if vv else 'fails'}" for kk, vv in v.items()) for k, v in predictions.items()]
    lines += ['', '## Promotion check (BITS_PROMOTION.md)', '', '| Size | Live | Candidate | Selections | Change | Package B | Change | Promote |', '| --- | --- | --- | ---: | ---: | ---: | ---: | --- |']
    for size, p in promotion.items():
        lines.append(f"| {size} | {p['live']['version']} ({p['live']['selections']:,}) | {p['candidate']} | {p['selections']:,} | {p['selection_change']:+.2%} | "
                     f"{p['package_bytes']:,} | {p['package_change']:+.2%} | {'yes' if p['meets_selection_rule'] and p['meets_package_rule'] else 'no'} |")
    (ROOT / 'RESULTS.md').write_text('\n'.join(lines) + '\n')
    print(json.dumps({k: {kk: vv for kk, vv in v.items() if kk in ('candidate', 'selections', 'selection_change', 'meets_selection_rule')} for k, v in promotion.items()}))


if __name__ == '__main__':
    main()
