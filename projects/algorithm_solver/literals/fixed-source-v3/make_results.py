#!/usr/bin/env python3
"""Writes RESULTS.md from the source-free v3 results, so no number is typed by hand.

    make_results.py [results folder] [output file]
"""
import gzip
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results'
OUTPUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / 'RESULTS.md'
SCENARIOS = {'s1-whole': 'Primary, any substring', 's2-nowhole': 'Control, two files', 'p2-nowhole': 'Control, two problems'}
ARMS = ('greedy-entry', 'greedy-byte', 'greedtok', 'pathpiece', 'bpe', 'freq-occ', 'freq-doc', 'lp-det', 'lp-bias')
BASELINES = {'bpe': 'BPE, shortest parse', 'bpe-ordinary': 'BPE, own segmentation', 'pathpiece': 'PathPiece', 'greedtok': 'GreedTok'}
CODINGS = {'raw': 'Raw table', 'merge': 'BPE merge pairs', 'deflate': 'Compressed dictionary, all arms'}


def load(name):
    path = RESULTS / name
    if name.endswith('.gz'):
        with gzip.open(path, 'rt') as handle:
            return json.load(handle)
    return json.loads(path.read_text())


def n(value):
    return '---' if value is None else f'{value:,}'


def pct(value, places=1):
    return '---' if value is None else f'{100 * value:.{places}f}%'


score, posthoc, regression = load('score.json'), load('posthoc.json'), load('regression.json')
checks = load('verification-summary.json')
cells = load('encoded.json.gz')['cells']
bar, P = score['kill_bar'], score['predictions']
failed = [key for key, item in P.items() if not item['held']]
frozen_allows = bar['k1_design_inversion'] or bar['k2_objective_inversion']
survives = posthoc['survives_equal_floor']


def cell(scenario, limit, budget, cap=None):
    return next(c for c in cells if c['scenario'] == scenario and c['L'] == limit and c['K'] == budget and c['B'] == cap)


w = ['# Fixed-source comparison v3: results\n']
w.append('Run `fixed-source-v3-r1`, frozen in [FREEZE.md](FREEZE.md) before any v3 dictionary was built on the real corpus. '
         'This file is generated by `make_results.py`. Sources, dictionaries, parses and solver output stay private.\n')
if frozen_allows and survives:
    verdict = 'The frozen kill bar passed, and it still passes with equal search floors. A full paper may proceed only if the prior-work comparison also holds.'
elif frozen_allows:
    verdict = 'The frozen kill bar passed, but the finding did not survive equal search floors. BITS should end with the benchmark note.'
else:
    verdict = 'The frozen kill bar did not pass. BITS should end with the benchmark note.'
w.append(f'**Decision.** {verdict}\n')
counts = []
for coding, label in CODINGS.items():
    parts = []
    for name in ('bpe', 'pathpiece'):
        row = posthoc['comparison'][coding].get(name, {}).get('s1-whole')
        if row:
            parts.append(f"{row['greedy_smaller']} of {row['cells']} cells against {BASELINES[name]}")
    counts.append(f"{label.lower()}: {', '.join(parts)}")
w.append('**Greedy against the main baselines.** Passing K2 does not mean greedy beats BPE or PathPiece. Under the primary rule, greedy is smaller in '
         + '; '.join(counts) + '.\n')
w.append(f"**Predictions.** {sum(item['held'] for item in P.values())} of {len(P)} held. Failed: {', '.join(failed) if failed else 'none'}.\n")
w.append('Everything here is in-sample on 400 paired Python and JavaScript solutions, with exact reconstruction. '
         'It says nothing about unseen code or model quality, and it claims no new algorithm or certificate. '
         'The certificate used in v1 and v2 is Theorem 1 of [Du and Chen](https://arxiv.org/abs/2609.35869).\n')

finish = (RESULTS / 'finish.log').read_text() if (RESULTS / 'finish.log').exists() else ''
if 'stage stopped at the LP limit' in finish:
    solved = {(row['policy'], row['K']) for row in score['lp']}
    missing = [f'{p} K={k}' for p in ('s1-whole', 's2-nowhole') for k in (256, 1024, 4096) if (p, k) not in solved]
    w.append('**Run note.** The LP stage reached its frozen 3-hour limit, so the pipeline stopped before verification. '
             f"Unfinished LP solves: {', '.join(missing) if missing else 'none'}. As the freeze requires, the run reports what finished: "
             'verification, regression, encoded sizes, scoring and the post-hoc checks were then run with the frozen code and commands '
             '(`finish.log`). The chain stage finished within its limit.\n')

w.append('## Checks\n')
w.append(f"- {checks['chains']} chains and {checks['single_dictionaries']} LP-rounded dictionaries were decoded byte for byte across {n(checks['cells'])} grid cells. "
         f"{len(checks['stopped_chains'])} chains stopped at a limit.")
w.append(f"- The greedy and frequency chains rebuilt {regression['identical']} of {regression['chains_compared']} comparable v2 chains entry for entry.\n")

w.append('## Frozen predictions\n')
w.append('| | Prediction | Outcome | Measured |')
w.append('| --- | --- | --- | --- |')
for key, item in P.items():
    w.append(f"| {key} | {item['text']} | {'held' if item['held'] else '**failed**'} | {pct(item['value'])} |")

w.append('\n## Frozen kill bar\n')
w.append(f"A full paper needs one finding in at least {pct(bar['threshold'], 0)} of feasible cells under all three rules. "
         'K1: design B or C is at least 1% smaller than A. K2: the token-best dictionary is at least 1% larger than the byte-best.\n')
w.append('| Rule | Feasible cells | Lowest total: A, B, C | K1 | K2 | A smaller than C |')
w.append('| --- | ---: | ---: | ---: | ---: | ---: |')
for key, name in SCENARIOS.items():
    row = score['by_scenario'][key]
    low = row['lowest_total']
    w.append(f"| {name} | {row['feasible']} | {low.get('A', 0)}, {low.get('B', 0)}, {low.get('C', 0)} | "
             f"{pct(row['k1_other_design_at_least_1pct_smaller'])} | {pct(row['k2_token_best_at_least_1pct_larger'])} | {pct(row['a_beats_c'])} |")
w.append(f"\nFrozen result: K1 {'passed' if bar['k1_design_inversion'] else 'did not pass'}, K2 {'passed' if bar['k2_objective_inversion'] else 'did not pass'}.\n")

w.append('## Total encoded bytes\n')
w.append('Primary rule, longest entry 16 bytes, no storage cap. A is one dictionary and table, B is one dictionary with a table per language, and C is one of each per language. '
         'The corpus is 264,908 bytes.\n')
w.append('| Entries | A | B | C | A tokens | Token-best dictionary, bytes |')
w.append('| ---: | ---: | ---: | ---: | ---: | ---: |')
for budget in (256, 1024, 4096):
    row = cell('s1-whole', 16, budget)
    w.append(f"| {budget:,} | {n(row['A']['A'])} | {n(row['B_design']['B'])} | {n(row['C']['bytes'])} | {n(row['A']['tokens'])} | {n(row['token_best']['A'])} |")
w.append('\n**Each method under design A,** same cells, total bytes:\n')
w.append('| Entries | ' + ' | '.join(ARMS) + ' |')
w.append('| ---: |' + ' ---: |' * len(ARMS))
for budget in (256, 1024, 4096):
    row = cell('s1-whole', 16, budget)['by_arm']
    w.append(f'| {budget:,} | ' + ' | '.join(n(row[a]['bytes']) if a in row else '---' for a in ARMS) + ' |')
w.append('\nAn LP value can come from a smaller solved size, because a smaller dictionary is legal at a larger budget. LP was solved only at 256, 1,024 and 4,096 entries.\n')

base, cut = cell('s1-whole', 16, 1024), cell('s1-whole-cuts', 16, 1024)
w.append('## Boundary-crossing ablation\n')
w.append(f"At 1,024 entries of up to 16 bytes, forbidding any piece from spanning a change of lexical class moves design A from {n(base['A']['A'])} to {n(cut['A']['A'])} bytes, "
         f"a {pct(cut['A']['A'] / base['A']['A'] - 1)} change. This explains where savings come from and has no part in the kill bar.\n")

w.append('## LP solves\n')
if score['lp']:
    w.append('| Rule | Entries | Solver status | LP value | Solve seconds |')
    w.append('| --- | ---: | --- | ---: | ---: |')
    for row in score['lp']:
        value = '---' if row['objective'] is None else f"{row['objective']:,.1f}"
        w.append(f"| {row['policy']} | {row['K']:,} | {row['status']} | {value} | {row['solve_seconds']:,.0f} |")
    w.append('\nAn LP value is numerical and is not a certificate.\n')
else:
    w.append('No LP solve finished.\n')
if score['lp_failures']:
    w.append('Failed solves: ' + '; '.join(score['lp_failures']) + '.\n')

w.append('## Post-hoc accounting checks\n')
w.append('These read-only checks were committed before any v3 result was read, after a review of the frozen accounting. They do not change the frozen result.\n')
w.append('Each row counts cells where greedy is smaller, tied, or larger than the baseline under design A. The median is how much larger the baseline is.\n')
w.append('| Dictionary coding | Baseline | Rule | Greedy smaller | Tied | Baseline smaller | Median |')
w.append('| --- | --- | --- | ---: | ---: | ---: | ---: |')
for coding, label in CODINGS.items():
    for name, title in BASELINES.items():
        for key in SCENARIOS:
            row = posthoc['comparison'][coding].get(name, {}).get(key)
            if row:
                w.append(f"| {label} | {title} | {key} | {row['greedy_smaller']} | {row['tied']} | {row['baseline_smaller']} | {pct(row['median_baseline_excess'], 2)} |")
w.append('\nMerge coding charges BPE one byte per alphabet symbol and two parent IDs per merged entry, and omits a small entry-count header. '
         'Merges that only recreate an existing string are encoder rules and are not stored.\n')
w.append('**Equal search floors.** K2 recomputed with the union floor available to token-best as well as byte-best:\n')
w.append('| Rule | Feasible | K2, frozen | K2, equal floor | Token-best replaced by union |')
w.append('| --- | ---: | ---: | ---: | ---: |')
for key, name in SCENARIOS.items():
    row = posthoc['equal_floor'][key]
    w.append(f"| {name} | {row['feasible']} | {pct(row['k2_frozen'])} | {pct(row['k2_equal_floor'])} | {row['token_best_replaced_by_union']} |")
carried = posthoc['lp_rows_carried_from_a_smaller_solved_K']
w.append(f"\nLP rows at an unsolved size, carried from a smaller solved dictionary: {', '.join(f'{k} {v}' for k, v in carried.items()) if carried else 'none'}.\n")

w.append('## What this does not show\n')
w.append('- Nothing here measures unseen code, a trained model or runtime speed.')
w.append('- All dictionary searches are heuristics, and no cell has a proved optimum.')
w.append('- The parser minimizes tokens, not bytes, so a byte-optimal parse could change these totals.')
w.append('- PathPiece and GreedTok are our implementations of the published methods.\n')
OUTPUT.write_text('\n'.join(w))
print('wrote', OUTPUT.name, sum(len(line.split()) for line in w), 'words')
