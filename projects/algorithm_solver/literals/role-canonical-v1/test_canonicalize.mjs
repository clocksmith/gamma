import assert from 'node:assert/strict';
import {canonicalize} from './canonicalize.mjs';
let tests=0;
const run=(source,mode='role')=>{const x=canonicalize(source,mode);assert(x.ast_verified);assert.equal(x.candidate_executions,0);tests++;return x;};
assert.match(run('function solve(input){let total=0;for(let index=0;index<input.length;index++)total+=input[index];return total;}').source,/for \(let i0/);
assert.match(run('function solve(input){return input+globalName;}').source,/globalName/);
assert.match(run('function solve(input){return input+p0;}').source,/solve\(p1\)/);
run('function solve(input){let a=[input];let m=new Map();let s=new Set();return [a,m,s];}');
run('function solve(input){let {fixed: local}=input;return local;}');
run('function solve(input){outer:for(let i=0;i<input;i++){if(i)break outer;}return input;}');
const shadow=run('function solve(x){let y=1;return [x,(()=>{let x=2;return x+y;})()];}');assert(shadow.changed_bindings.length>=2);
assert.match(run('function solve(x){return {x};}').source,/\{\s*x\s*\}/);
assert.match(run('function solve(input){const f=()=>input;return f;}').source,/const f/);
for(const mode of ['role','format'])for(const source of ['function solve(x){return x.name;}','function solve(x){return x.toString();}','function solve(x){return eval(x);}']){assert.throws(()=>canonicalize(source,mode));tests++;}
const special=run('function solve(input){"use strict";let number=9007199254740993n;let pattern=/a+/gi;return [number,pattern,`x${input}`,{fixed:input}];}');
assert.match(special.source,/9007199254740993n/);assert.match(special.source,/fixed:/);assert.match(special.source,/use strict/);
run('function solve(x){return [1e400,-0,0x10,x];}');
assert.equal(run('function solve(x){return x+1;}','format').changed_bindings.length,0);
assert.throws(()=>canonicalize('function solve(x){return x;}','unknown'));tests++;
console.log(JSON.stringify({synthetic_ast_tests:tests,candidate_executions:0}));
