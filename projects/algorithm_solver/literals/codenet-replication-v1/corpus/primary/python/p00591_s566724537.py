while True:
    n = int(input())
    if not n:
        break
    #map???????????£????????£??¨????????????????°???????????????????????????????????????¨
    f = [[int(j) for j in input().split()] for i in range(n)]
    ans = max(min(f[i]) for i in range(n))
    tans = [max(f[i][j] for i in range(n)) for j in range(n)]
    for i in range(n):
        if tans[i] == ans:
            break
    else:
        ans = 0
    print(ans)