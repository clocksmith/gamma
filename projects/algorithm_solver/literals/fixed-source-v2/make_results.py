#!/usr/bin/env python3
"""Writes RESULTS.md from the source-free results, so no number is typed by hand.

    make_results.py [results folder]
"""
import gzip
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'results'
NAMES = {'python': 'Python', 'javascript': 'JavaScript', 'both': 'Both'}
POLICY = {'s1-whole': 'Unrestricted', 's2-nowhole': 'Two-file control'}


def load(name):
    path = RESULTS / name
    if name.endswith('.gz'):
        with gzip.open(path, 'rt') as handle:
            return json.load(handle)
    return json.loads(path.read_text())


def n(value):
    return '---' if value is None else f'{value:,}'


def pct(value, places=1):
    return '---' if value is None else f'{100 * value:.{places}f}%'


def cap(value):
    return 'none' if value is None else f'{value // 1024} KiB'


summary, closeout = load('summary.json.gz'), load('closeout.json')
sharing_check, regression = load('sharing-check.json'), load('regression.json')
P = summary['predictions']
E = summary['endpoints']
lower, higher = closeout['reduction_when_lower'], closeout['increase_when_higher']
outcomes = closeout['paired_outcomes']
under, over = closeout['cells_storing_less_than_half'], closeout['cells_storing_at_least_half_the_corpus']
gaps = {p: [b['gap'] for b in closeout['bounds'] if b['policy'] == p] for p in POLICY}
held = sum(item['held'] for item in P.values())
failed = [key for key, item in P.items() if not item['held']]
r3 = P['R3']
wide = closeout['per_file']['L64-K4096']
s1, s2 = sharing_check['by_policy']['s1-whole'], sharing_check['by_policy']['s2-nowhole']

w = []
w.append('# Fixed-source retest v2: results\n')
w.append(f"Run `{summary['run']}`, frozen in [FREEZE.md](FREEZE.md) before any v2 dictionary was mined. "
         'This file is generated by `make_results.py` from `results/`. Sources, dictionaries, parses and certificates stay private.\n')
w.append('**Result.** Dropping the two-file rule changes little at ordinary budgets and a lot only when the dictionary starts '
         f"storing the corpus. At 256 entries of up to 16 bytes, both rules reach {n(E['E1'][0]['primary'])} tokens. "
         f"At 4,096 entries of up to 64 bytes, the unrestricted rule uses {pct(r3['reduction'])} fewer tokens "
         f"({n(r3['primary'])} against {n(r3['control'])}), but its dictionary stores {n(wide['primary_stored'])} bytes against "
         f"{n(wide['control_stored'])} on a 264,908-byte corpus. That is mostly memorization, so token count alone cannot rank these dictionaries.\n")
w.append(f"**Predictions.** {held} of {len(P)} held. Failed: {', '.join(failed) if failed else 'none'}.\n")
w.append('Everything here is in-sample on 400 paired Python and JavaScript solutions. It says nothing about unseen code, '
         'model output or end-to-end compression. No optimum is proved.\n')

w.append('## Checks\n')
w.append(f"- {summary['chains']} chains and {summary['polished_dictionaries']} polished dictionaries were decoded byte for byte across "
         f"{n(summary['cells'])} grid cells. {len(summary['stopped_chains'])} chains stopped at a limit.")
w.append(f"- The control rebuilt {regression['identical']} of {regression['chains_compared']} comparable v1 chains entry for entry.")
w.append(f"- {sharing_check['splits_decoded']} shared-against-separate splits were decoded.")
w.append(f"- {len(closeout['bounds'])} dual certificates were recomputed in exact integers. The certificate is Theorem 1 of "
         '[Du and Chen](https://arxiv.org/abs/2609.35869), which we use and do not claim.')
w.append('- Unrestricted reachability matched its closed form at every tested length.\n')

w.append('## Frozen predictions\n')
w.append('| | Prediction | Outcome | Measured |')
w.append('| --- | --- | --- | --- |')
w.append(f"| R1 | {P['R1']['text']} | {'held' if P['R1']['held'] else '**failed**'} | {n(P['R1']['primary'])} against {n(P['R1']['control'])} |")
w.append(f"| R2 | {P['R2']['text']} | {'held' if P['R2']['held'] else '**failed**'} | {P['R2']['primary']} against {P['R2']['control']} files |")
w.append(f"| R3 | {P['R3']['text']} | {'held' if P['R3']['held'] else '**failed**'} | {n(P['R3']['primary'])} against {n(P['R3']['control'])} |")
w.append(f"| R4 | {P['R4']['text']} | {'held' if P['R4']['held'] else '**failed**'} | every feasible budget |")
w.append(f"| R5 | {P['R5']['text']} | {'held' if P['R5']['held'] else '**failed**'} | {P['R5']['whole_file_entries']} whole-file entries |\n")

w.append('## Primary endpoints\n')
w.append('**E1:** both languages, 256 entries, up to 16 bytes, lowest verified total tokens.\n')
w.append('| Byte cap | Unrestricted | Two-file control | Reduction |')
w.append('| --- | ---: | ---: | ---: |')
for row in E['E1']:
    w.append(f"| {cap(row['B'])} | {n(row['primary'])} | {n(row['control'])} | {pct(row['reduction'])} |")
w.append('\n**E2:** both languages, 4,096 entries, up to 16 bytes, no single characters: files spelled by one dictionary, of 800.\n')
w.append('| Byte cap | Unrestricted | Two-file control |')
w.append('| --- | ---: | ---: |')
for row in E['E2']:
    w.append(f"| {cap(row['B'])} | {row['primary']} | {row['control']} |")
w.append('\nThe unrestricted search spells fewer files at the 16 and 32 KiB caps, so dropping the rule did not help this heuristic when bytes were scarce. '
         'These are search results, not limits.\n')

w.append('## Paired v2 against the control and v1\n')
w.append(f"Across {n(closeout['paired_cells'])} matched budgets, the unrestricted best is lower in {outcomes['primary lower']}, "
         f"equal in {outcomes['equal']} and higher in {outcomes['primary higher']}. A larger candidate set cannot be worse at the optimum, so those "
         f"{outcomes['primary higher']} cells are search failures. Where it is lower, the median reduction is {pct(lower['median'], 2)}, the 90th percentile "
         f"{pct(lower['p90'])} and the maximum {pct(lower['max'])}. Where it is higher, the median increase is {pct(higher['median'], 2)} and the maximum {pct(higher['max'])}.\n")
w.append(f"The large wins sit where the dictionary stores much of the corpus. In the {over['n']} cells storing at least half of it, the reduction is "
         f"{pct(over['reduction']['min'])} to {pct(over['reduction']['max'])}. In the other {n(under['n'])} cells the median change is {pct(under['median'], 2)} "
         f"and the 90th percentile {pct(under['p90'])}.\n")
compare = closeout['v1_vs_v2_control_best']
w.append(f"Against v1, the control's best result is equal in {n(compare.get('equal', 0))} cells and lower in {compare.get('v2 control lower', 0)}, "
         'where the time-limited local search found a little more.\n')

w.append('**Broad effect or a few large wins?** Per-file token change against the control, both languages, no byte cap:\n')
w.append('| Longest entry, entries | Files better | Same | Worse | Net tokens saved | Top 10% of files, share of gains | Stored bytes, unrestricted | Control |')
w.append('| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |')
for key, row in closeout['per_file'].items():
    limit, size = key[1:].split('-K')
    w.append(f"| {limit} bytes, {int(size):,} | {row['improved']} | {row['unchanged']} | {row['worse']} | {n(row['net_tokens_saved'])} | "
             f"{pct(row['top_10pct_share_of_gross'], 0)} | {n(row['primary_stored'])} | {n(row['control_stored'])} |")
w.append('\nAt moderate budgets the effect is uneven: some files gain and many lose as entries are reallocated. It becomes broad at the largest budget, where 792 of 800 files gain and the dictionary stores about three quarters of the corpus size.\n')

w.append('## Certified bounds\n')
w.append('Entries of up to 16 bytes, no byte cap. The best dictionary is a verified construction. The lower bound is rechecked in exact integers. No cell is a proved optimum.\n')
w.append('| Rule | Corpus | Entries | Best found | Lower bound | Gap |')
w.append('| --- | --- | ---: | ---: | ---: | ---: |')
for row in sorted(closeout['bounds'], key=lambda b: (b['policy'] != 's1-whole', ('both', 'python', 'javascript').index(b['corpus']), b['K'])):
    w.append(f"| {POLICY[row['policy']]} | {NAMES[row['corpus']]} | {row['K']:,} | {n(row['best'])} | {n(row['lower_bound'])} | {pct(row['gap'])} |")
w.append(f"\nGaps are {pct(min(gaps['s1-whole']))} to {pct(max(gaps['s1-whole']))} unrestricted and {pct(min(gaps['s2-nowhole']))} to {pct(max(gaps['s2-nowhole']))} under the control. "
         'At 16 bytes on both languages the unrestricted problem has about five times as many candidate strings at the same iteration count, so its bound may simply be looser. The wider gaps do not show that better unrestricted dictionaries exist.\n')

reach = summary['reachability']['both']
w.append('## Without single characters\n')
w.append('Files with no parse under the rule at any dictionary size, of 800:\n')
w.append('| Longest entry | Unrestricted | Two-file control |')
w.append('| ---: | ---: | ---: |')
for limit in ('2', '4', '8', '16', '32', '64'):
    w.append(f"| {limit} | {reach['s1-whole'][limit]['proved_unreachable']} | {reach['s2-nowhole'][limit]['proved_unreachable']} |")
w.append('\nReachability ignores the entry and byte budgets, so it does not mean one dictionary can spell those files.\n')

w.append('## Shared against separate\n')
w.append(f"One shared dictionary beat two separate ones in {s1['shared_wins']} of {s1['splits']} unrestricted budgets and {s2['shared_wins']} of {s2['splits']} control budgets. "
         'The direction is guaranteed for optimal dictionaries, because the union of two separate dictionaries fits the same combined budget. Only the size of the gain is empirical. ')
losses = closeout['primary_sharing_losses']
w.append('The unrestricted exceptions are search failures: ' + '; '.join(
    f"{r['L']} bytes, {r['K']:,} entries, {cap(r['B'])} (shared {n(r['shared'])}, separate {n(r['separate'])})" for r in losses) + '.\n')

w.append('## What this does not show\n')
w.append('- Nothing here measures unseen code, a trained model or total encoded size.')
w.append('- Token counts ignore the cost of storing the dictionary, which is why the largest unrestricted wins are not compression claims.')
w.append('- All search arms are heuristics, and no cell has a proved optimum.')
w.append('- The two-file rule counts files, so a string in one problem\'s Python and JavaScript solutions passes it. A problem-level rule is left to a separately frozen experiment.\n')
(HERE / 'RESULTS.md').write_text('\n'.join(w))
print('wrote RESULTS.md', sum(len(line.split()) for line in w), 'words')
