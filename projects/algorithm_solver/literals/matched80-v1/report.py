"""Rebuild results.json and RESULTS.md from run-v1 artifacts. Reads only; safe to rerun."""
import hashlib
import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent
LIT = ROOT.parent
RUN = ROOT / 'run-v1'
POOLS, STYLES, SIZES = ('designed', 'mined', 'combined'), ('canonical', 'compact'), (128, 256)
DECODER = ['../readable-v1/literal_codec.py', '../pass2/working/bitpack.py']


def load(path):
    return json.loads(path.read_text())


def arm(name):
    m = load(RUN / name / 'manifest.json')
    return m['metrics'], {str(r['id']): r['selections'] for r in m['programs']}


def groups(labels, per_problem):
    out = {'difficulty': defaultdict(list), 'primary_tag': defaultdict(list), 'tag': defaultdict(list)}
    for pid, n in per_problem.items():
        lab = labels[pid]
        out['difficulty'][lab['difficulty']].append(n)
        out['primary_tag'][lab['primary_tag']].append(n)
        for t in lab['tags']:
            out['tag'][t].append(n)
    return {k: {g: {'problems': len(v), 'selections': sum(v), 'median': statistics.median(v)} for g, v in sorted(d.items())} for k, d in out.items()}


def main():
    run = load(RUN / 'run.json')
    labels = load(ROOT / 'labels/labels.json')['labels']
    decoder = {rel: {'bytes': (ROOT / rel).stat().st_size, 'sha256': hashlib.sha256((ROOT / rel).read_bytes()).hexdigest()} for rel in DECODER}
    arms, breakdowns = {}, {}
    for pool in POOLS:
        for style in STYLES:
            res = load(RUN / f'fixed-{pool}-{style}-resources.json')
            for size in SIZES:
                name = f'fixed-{pool}-{style}-{size}'
                metrics, per = arm(name)
                arms[name] = {**metrics, 'trajectory': res}
                breakdowns[name] = groups(labels, per)
        for size in SIZES:
            name = f'joint-{pool}-{size}'
            metrics, per = arm(name)
            arms[name] = {**metrics, 'trajectory': load(RUN / f'joint-{pool}-{size}-resources.json')}
            breakdowns[name] = groups(labels, per)
    control = {style: load(RUN / f'control-scale-v2-{style}.json') for style in STYLES}
    sel = lambda name: arms[name]['selections']
    designed_entries = lambda name: arms[name]['entries_by_provenance'].get('designed', 0)
    predictions = {
        'P1 combined <= mined on canonical': {str(n): {'combined': sel(f'fixed-combined-canonical-{n}'), 'mined': sel(f'fixed-mined-canonical-{n}'),
                                                        'holds': sel(f'fixed-combined-canonical-{n}') <= sel(f'fixed-mined-canonical-{n}')} for n in SIZES},
        'P2 designed > mined': {f'{s}-{n}': {'designed': sel(f'fixed-designed-{s}-{n}'), 'mined': sel(f'fixed-mined-{s}-{n}'),
                                              'holds': sel(f'fixed-designed-{s}-{n}') > sel(f'fixed-mined-{s}-{n}')} for s in STYLES for n in SIZES},
        'P3 fewer designed-piece matches in compact combined': {str(n): {'compact': designed_entries(f'fixed-combined-compact-{n}'),
                                                                   'canonical': designed_entries(f'fixed-combined-canonical-{n}'),
                                                                   'holds': designed_entries(f'fixed-combined-compact-{n}') < designed_entries(f'fixed-combined-canonical-{n}')} for n in SIZES},
        'P4 joint <= best fixed': {f'{p}-{n}': {'joint': sel(f'joint-{p}-{n}'), 'best_fixed': min(sel(f'fixed-{p}-{s}-{n}') for s in STYLES),
                                                 'holds': sel(f'joint-{p}-{n}') <= min(sel(f'fixed-{p}-{s}-{n}') for s in STYLES)} for p in POOLS for n in SIZES},
    }
    results = {'schema': 'gamma.matched80.results.v1', 'run': {k: run[k] for k in ('complete', 'host', 'python', 'platform', 'elapsed_seconds', 'contract_sha256', 'runner_sha256')},
               'decoder': decoder, 'control': control, 'predictions': predictions, 'arms': arms, 'breakdowns': breakdowns}
    (ROOT / 'results.json').write_text(json.dumps(results, indent=2, sort_keys=True) + '\n')
    (ROOT / 'RESULTS.md').write_text(markdown(results))
    print(json.dumps({'arms': len(arms), 'complete': run['complete']}))


def markdown(r):
    lines = ['# Matched 80-problem results', '', f"Generated by `report.py` from `run-v1/` (run complete: {r['run']['complete']}; host {r['run']['host']}, Python {r['run']['python']}).",
             'Development evidence on 80 exposed problems; see [README.md](README.md) for the frozen design and limits.', '',
             '## Reproduction control', '', '| Style | Size | Rerun selections | Stored | Identical dictionary |', '| --- | --- | ---: | ---: | --- |']
    for style, rows in r['control'].items():
        for size, c in rows.items():
            lines.append(f"| {style} | {size} | {c['selections']:,} | {c['stored_selections']:,} | {c['identical_dictionary']} |")
    lines += ['', '## Arms', '', 'Coverage first; all costs shown, none blended. Package bytes include the dictionary and 41-byte packet headers; the shared decoder is listed separately.', '',
              '`entries_by_provenance` classifies each entry by its text: "designed" means the string equals a designed piece, whichever proposer found it. Mined-only arms also rediscover some designed strings by mining; they never receive designed candidates.', '',
              '| Arm | Covered | Entries (matches designed / other learned / fallback) | Selections | Input bits | Median / p95 | Dictionary B | Package B | Fallback sel. | Fallback chars | Trials | Search s |',
              '| --- | ---: | --- | ---: | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: |']
    for name, a in r['arms'].items():
        p = a['entries_by_provenance']
        lines.append(f"| {name} | {a['covered_programs']}/80 | {a['entries']} ({p.get('designed', 0)}/{p.get('mined', 0)}/{p.get('fallback', 0)}) | {a['selections']:,} | {a['total_input_bits']:,} | "
                     f"{a['median_selections']} / {a['p95_selections']} | {a['dictionary_bytes']:,} | {a['package_bytes']:,} | {a['single_character_selection_fraction']:.1%} | "
                     f"{a['fallback_character_fraction']:.1%} | {a['trajectory']['trials']:,} | {a['trajectory']['search_seconds']:.1f} |")
    lines += ['', 'Fixed 128 and 256 arms are snapshots of one trajectory, so their trials and seconds are shared. Joint rows show their own trials; inherited fixed-search costs are in `results.json`.',
              '', '## Predictions (as preregistered)', '']
    for title, rows in r['predictions'].items():
        lines.append(f'**{title}**: ' + '; '.join(f"{k}: {'holds' if v['holds'] else 'fails'} ({', '.join(f'{kk} {vv:,}' for kk, vv in v.items() if kk != 'holds')})" for k, v in rows.items()))
        lines.append('')
    lines += ['## Decoder storage (shared, constant across arms)', '']
    for rel, d in r['decoder'].items():
        lines.append(f"- `{rel}`: {d['bytes']:,} bytes, SHA-256 `{d['sha256'][:16]}...`")
    lines += ['', '## Difficulty breakdown (selections; Medium and Hard cells are small)', '', '| Arm | Easy (69) | Medium (9) | Hard (2) |', '| --- | ---: | ---: | ---: |']
    for name, b in r['breakdowns'].items():
        d = b['difficulty']
        lines.append(f"| {name} | " + ' | '.join(f"{d[k]['selections']:,} (median {d[k]['median']})" if k in d else '-' for k in ('Easy', 'Medium', 'Hard')) + ' |')
    lines += ['', 'Per-tag and primary-tag breakdowns for every arm are in `results.json` under `breakdowns`.', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    main()
