"""Write RESULTS.md from run-v1 manifests and verify.py's verification.json."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
LIVE_8, LIVE_7 = 57717, 79280


def fmt(v):
    if v is None:
        return '-'
    if isinstance(v, float):
        return f'{v:,.2f}'
    return f'{v:,}' if isinstance(v, int) else str(v)


def solver(rec):
    if not rec:
        return '-'
    gap = rec.get('mip_gap')
    return f"status {rec['status']}, {rec['seconds']:,.0f} s" + (f", gap {gap:.4f}" if gap is not None else '')


def main():
    folder = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'run-v1'
    checks = {r['job']: r for r in json.loads((folder / 'verification.json').read_text())}
    jobs = {p.name: json.loads((p / 'manifest.json').read_text()) for p in sorted(folder.iterdir()) if (p / 'manifest.json').exists()}
    lines = ['# sixbit-v1 results', '', f'Generated by report.py from `{folder.name}` and `verification.json`.', '',
             '## A: exact coverage', '',
             '| Job | Verified lower bound | Minimum found | Optimum proven | Six-bit exact coverage | LP | MILP |',
             '| --- | ---: | ---: | --- | --- | --- | --- |']
    for name, m in jobs.items():
        if m['experiment'] != 'A':
            continue
        c = checks[name]
        verdict = 'impossible' if c.get('six_bit_exact_coverage_impossible') else ('possible' if c.get('entries', 99) <= 64 else 'unresolved')
        lines.append(f"| {name} | {c.get('min_entries_at_least', '-')} (bound {fmt(c.get('bound'))}) | {fmt(c.get('entries'))} | "
                     f"{'yes' if c.get('optimum_proven') else 'no'} | {verdict} | {m['lp']['seconds']:,.0f} s | {solver(m.get('milp'))} |")
    lines += ['', '## B: maximum coverage with 64 entries', '',
              '| Job | Covered | Coverage upper bound | Entries | Selections | Presses (x7) | Package bytes | Median / p95 / max per problem | Phase 1 | Phase 2 |',
              '| --- | ---: | ---: | ---: | ---: | ---: | ---: | --- | --- | --- |']
    for name, m in jobs.items():
        if m['experiment'] != 'B':
            continue
        c, d = checks[name], m.get('selection_distribution') or {}
        lines.append(f"| {name} | {c.get('covered', '-')} | {c.get('coverage_at_most', '-')} | {fmt(c.get('entries'))} | {fmt(c.get('selections'))} | "
                     f"{fmt(c.get('presses'))} | {fmt(c.get('package_bytes'))} | {d.get('median', '-')} / {d.get('p95', '-')} / {d.get('max', '-')} | "
                     f"{solver(m.get('milp_coverage'))} | {solver(m.get('milp_selections'))} |")
    for name, m in jobs.items():
        if m['experiment'] == 'B':
            lines += ['', f"{name} uncovered: {', '.join('#' + p for p in m.get('uncovered_programs', [])) or 'none'}"]
    lines += ['', '## C: literal-escape6-v1 (63 entries + ESC)', '',
              '| Job | Covered | Presses | Verified press lower bound | vs live 8-bit 57,717 | Selections | Escapes | Package bytes (with decoder / without) | MILP |',
              '| --- | ---: | ---: | ---: | --- | ---: | ---: | --- | --- |']
    for name, m in jobs.items():
        if m['experiment'] != 'C':
            continue
        c = checks[name]
        delta = (c['presses'] - LIVE_8) / LIVE_8
        lines.append(f"| {name} | {c['covered']} | {fmt(c['presses'])} | {fmt(c.get('presses_at_least'))} | {delta:+.1%} | {fmt(c['selections'])} | "
                     f"{fmt(c['escapes'])} | {fmt(c['package_bytes'])} / {fmt(c['package_bytes_without_decoder'])} | {solver(m.get('milp'))} |")
    for name, m in jobs.items():
        if m['experiment'] == 'C':
            lines += ['', f"{name} escaped characters: {' '.join(repr(ch) for ch in m['escaped_characters'])}"]
    lines += ['', '## Per-problem counts (compact)', '']
    shown = [n for n, m in jobs.items() if m['style'] == 'compact' and m['experiment'] in ('B', 'C')]
    lines += ['| Problem | ' + ' | '.join(shown) + ' |', '| --- |' + ' ---: |' * len(shown)]
    for p in map(str, json.loads((ROOT.parent / 'matched80-v1/labels/ids.json').read_text())):
        row = []
        for n in shown:
            m = jobs[n]
            if m['experiment'] == 'C':
                v = m['programs'][p]
                row.append(f"{v['presses']} ({v['escapes']} esc)")
            else:
                row.append(fmt(m['selections'].get(p)) + ' sel' if p in m['selections'] else 'uncovered')
        lines.append(f'| #{p} | ' + ' | '.join(row) + ' |')
    lines += ['', 'B cells are six-bit selections (7 presses each); C cells are presses with escaped characters.', '']
    (ROOT / 'RESULTS.md').write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
