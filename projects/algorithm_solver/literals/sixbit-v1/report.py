"""Write RESULTS.md from run-v1 (Mars, frozen), run-jupiter-v1 (compute supplement),
their verification.json files and macro-entries.json."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
LITERALS = ROOT.parent
RUNS = (('run-v1', 'Mars (frozen)'), ('run-jupiter-v1', 'Jupiter (supplement)'))


def fmt(v):
    if v is None:
        return '-'
    if isinstance(v, float):
        return f'{v:,.2f}'
    return f'{v:,}' if isinstance(v, int) else str(v)


def solver(rec):
    if not rec:
        return '-'
    text = 'optimal' if rec['status'] == 0 else ('time limit' if rec['status'] == 1 else f"status {rec['status']}")
    gap = rec.get('mip_gap')
    if rec['status'] != 0 and gap is not None:
        text += f', gap {gap:.3f}'
    return f"{text}, {rec['seconds']:,.0f} s"


def live_selections():
    """Per-problem selections of the live and frozen-comparison profiles on these sources."""
    v1 = json.loads((LITERALS / 'scale-v2/search-v2/compact-marginal-256/manifest.json').read_text())['programs']
    seven = json.loads((LITERALS / 'guides-joint80-v2/package.json').read_text())['programs']
    eight = json.loads((LITERALS / 'guides-joint80-8-v2/package.json').read_text())['programs']
    return {'8-bit v1 (bar at freeze)': (9, {str(p['id']): len(p['sequence']) for p in v1}),
            '8-bit v2 (live now)': (9, {str(p['problem_id']): p['selections'] for p in eight}),
            '7-bit v2 (live)': (8, {str(p['problem_id']): p['selections'] for p in seven})}


def main():
    loaded = []
    for name, label in RUNS:
        folder = ROOT / name
        if not (folder / 'verification.json').exists():
            continue
        checks = {r['job']: r for r in json.loads((folder / 'verification.json').read_text())}
        for job in sorted(p for p in folder.iterdir() if (p / 'manifest.json').exists()):
            loaded.append((name, label, json.loads((job / 'manifest.json').read_text()), checks[job.name]))
    macro = {(r['run'], r['job']): r for r in json.loads((ROOT / 'macro-entries.json').read_text())['rows']}
    category = lambda run, job: macro[(run, job)]['category'] if (run, job) in macro else '-'
    near = lambda run, job: macro[(run, job)]['near_whole_program_entries'] if (run, job) in macro else '-'
    live = live_selections()
    lines = ['# sixbit-v1 results', '',
             'Generated by report.py. Mars `run-v1` is the frozen record ([FREEZE.md](FREEZE.md)); Jupiter',
             '`run-jupiter-v1` is the declared compute supplement ([FREEZE-jupiter.md](FREEZE-jupiter.md)).',
             'Every number below was rechecked by `verify_amended.py` (packets decoded, rules and budgets',
             'checked, Lagrangian bounds recomputed from the stored potentials over every eligible',
             'substring). Category uses the BITS macro rule; near-whole counts entries found in one',
             'program and at least half its length (a reporting addition).', '',
             'Press figures use the frozen protocol (frame bit plus code). Since 256one `fff69c5` (2026-10-22)',
             'BITS enters a literal as its ID alone, so live 7-bit v2 is now 69,370 presses and 8-bit v2 49,288;',
             'see the dated note in [README.md](README.md).', '',
             '## A: exact coverage (minimum entries)', '',
             '| Run | Job | Certified lower bound | Smallest vocabulary found | Optimum proven | 64 entries enough? | Category (macro / near-whole) | LP | MILP |',
             '| --- | --- | ---: | ---: | --- | --- | --- | --- | --- |']
    for run, label, m, c in loaded:
        if m['experiment'] != 'A':
            continue
        lower = c.get('min_entries_at_least')
        milp = m.get('milp') or {}
        # No certificate (the LP hit its limit) but HiGHS closed the MILP: the optimum rests on the solver alone.
        solver_only = lower is None and milp.get('status') == 0 and milp.get('mip_gap') == 0 and c.get('entries') is not None
        proven = 'yes' if c.get('optimum_proven') else ('solver only (gap 0), not certified' if solver_only else 'no')
        verdict = ('no (certified)' if c.get('six_bit_exact_coverage_impossible') else 'yes' if c.get('entries', 999) <= 64
                   else 'no (solver only, not certified)' if solver_only else 'unresolved')
        lines.append(f"| {label} | {m['job']} | {fmt(lower)} | {fmt(c.get('entries'))} | {proven} | {verdict} | "
                     f"{category(run, m['job'])} ({macro.get((run, m['job']), {}).get('macro_entries', '-')} / {near(run, m['job'])}) | {solver(m['lp'])} | {solver(m.get('milp'))} |")
    lines += ['', '## B: maximum coverage with 64 entries', '',
              '| Run | Job | Covered | Certified coverage upper bound | Selections | Presses (x7) | Package bytes | Median / p95 / max | Category | Phase 1 | Phase 2 |',
              '| --- | --- | ---: | ---: | ---: | ---: | ---: | --- | --- | --- | --- |']
    for run, label, m, c in loaded:
        if m['experiment'] != 'B':
            continue
        d = m.get('selection_distribution') or {}
        lines.append(f"| {label} | {m['job']} | {c.get('covered')} | {c.get('coverage_at_most', '-')} | {fmt(c.get('selections'))} | {fmt(c.get('presses'))} | "
                     f"{fmt(c.get('package_bytes'))} | {d.get('median')} / {d.get('p95')} / {d.get('max')} | {category(run, m['job'])} | "
                     f"{solver(m.get('milp_coverage'))} | {solver(m.get('milp_selections'))} |")
    lines += ['', 'Same covered programs, live profiles (presses = selections x frame width):', '',
              '| Run | Job | Six-bit presses | ' + ' | '.join(live) + ' |', '| --- | --- | ---: |' + ' ---: |' * len(live)]
    for run, label, m, c in loaded:
        if m['experiment'] != 'B':
            continue
        covered = m['covered_programs']
        cells = [f"{fmt(w * sum(sel[p] for p in covered))}" for w, sel in live.values()]
        lines.append(f"| {label} | {m['job']} | {fmt(c['presses'])} | " + ' | '.join(cells) + ' |')
        lines.append(f"| | uncovered | {', '.join('#' + p for p in m['uncovered_programs'])} |" + ' |' * len(live))
    lines += ['', '## C: literal-escape6-v1 (63 entries + ESC, all 80 programs)', '',
              '| Run | Job | Presses | Certified press lower bound | Selections | Escapes | Package bytes (with / without decoder) | Category (macro / near-whole) | MILP |',
              '| --- | --- | ---: | ---: | ---: | ---: | --- | --- | --- |']
    for run, label, m, c in loaded:
        if m['experiment'] != 'C':
            continue
        lines.append(f"| {label} | {m['job']} | {fmt(c['presses'])} | {fmt(c.get('presses_at_least'))} | {fmt(c['selections'])} | {fmt(c['escapes'])} | "
                     f"{fmt(c['package_bytes'])} / {fmt(c['package_bytes_without_decoder'])} | {category(run, m['job'])} "
                     f"({macro.get((run, m['job']), {}).get('macro_entries', '-')} / {near(run, m['job'])}) | {solver(m.get('milp'))} |")
    full = {k: w * sum(sel.values()) for k, (w, sel) in live.items()}
    lines += ['', 'Whole-cohort presses of live profiles: ' + '; '.join(f'{k} {fmt(v)}' for k, v in full.items()) + '.']
    for run, label, m, c in loaded:
        if m['experiment'] == 'C':
            lines += ['', f"{label} {m['job']} escaped characters: {' '.join(repr(ch) for ch in m['escaped_characters'])}"]
    frozen = {m['job']: m for run, _, m, _ in loaded if run == 'run-v1'}
    shown = [j for j in ('b-w-compact', 'b-u-compact', 'c-w-compact', 'c-u-compact') if j in frozen]
    lines += ['', '## Per-problem counts (Mars run-v1, compact)', '',
              '| Problem | ' + ' | '.join(shown) + ' | 8-bit v2 live |', '| --- |' + ' ---: |' * (len(shown) + 1)]
    for p in map(str, json.loads((LITERALS / 'matched80-v1/labels/ids.json').read_text())):
        row = []
        for j in shown:
            m = frozen[j]
            if m['experiment'] == 'C':
                v = m['programs'][p]
                row.append(f"{v['presses']} ({v['escapes']} esc)")
            else:
                row.append(f"{m['selections'][p]} sel" if p in m['selections'] else 'uncovered')
        lines.append(f'| #{p} | ' + ' | '.join(row) + f" | {live['8-bit v2 (live now)'][1][p]} sel |")
    lines += ['', 'B cells are six-bit selections (7 presses each); C cells are presses and escaped characters;',
              'the last column is the live 8-bit profile (9 presses each).', '']
    (ROOT / 'RESULTS.md').write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
