import importlib.util
from pathlib import Path
import random
import sys
import unittest

HERE = Path(__file__).resolve().parent
sys.path.insert(0,str(HERE))
import codec as c
import search as s


class MixedSearchTests(unittest.TestCase):
    def test_exhaustive_literal_paths_with_optional_characters(self):
        rng = random.Random(31)
        words = ['a','b','aa','ab','ba','bb','aba']
        for _ in range(60):
            text = ''.join(rng.choice('ab') for _ in range(rng.randrange(1,7)))
            keys = c.order(c.literal(w) for w in rng.sample(words,rng.randrange(1,len(words)+1)))
            def paths(pos):
                if pos == len(text):
                    yield ()
                for index,key in enumerate(keys):
                    if text.startswith(key[1:],pos):
                        for suffix in paths(pos+len(key)-1):
                            yield (index,)+suffix
            possible = list(paths(0))
            nodes = {'bodies':[],'prefix':[],'identifier':[]}
            if possible:
                expected = min(possible,key=lambda x:(len(x),x))
                got = c.encode_source(text,nodes,keys)
                self.assertEqual(got['tokens'],[keys[i] for i in expected])
            else:
                with self.assertRaises(ValueError):
                    c.encode_source(text,nodes,keys)

    def test_cache_reacts_to_both_constructor_kinds(self):
        texts = {'p':'function solve(a,b){let q=a.length;return q+b.length}',
                 'q':'function solve(c,d){let r=c.length;return r+d.length}'}
        nodes = c.extract(texts)
        initial = [c.literal(x) for x in c.ALPHABET]
        budget = s.Budget(100,20)
        parent = s.evaluate(texts,nodes,initial,budget)
        for kind,family in (('P','prefix'),('I','identifier')):
            constructors = [n['key'] for group in nodes.values() for n in group[family] if n['key']]
            keys = initial+constructors
            cached = s.evaluate(texts,nodes,keys,budget,parent)
            fresh = s.evaluate(texts,nodes,keys,budget)
            self.assertEqual(cached['rows'],fresh['rows'])
            self.assertLessEqual(fresh['selections'],parent['selections'])
            self.assertTrue(all(k[0] in ('L',kind) for k in fresh['keys']))

    def test_pool_support_counts_distinct_programs(self):
        text = 'function solve(a,b){let q=a.length;return q+b.length}'
        nodes = c.extract({'p':text})
        constructors,_,_ = s.pool({'p':text},nodes,set(nodes['p']['bodies']))
        self.assertFalse(constructors['P'])
        self.assertFalse(constructors['I'])
        texts = {'p':text,'q':text}
        nodes = c.extract(texts)
        constructors,_,support = s.pool(texts,nodes,set(nodes['p']['bodies']))
        self.assertTrue(constructors['P'])
        self.assertTrue(constructors['I'])
        self.assertTrue(all(v == 2 for v in support.values()))

    def test_bounded_search_never_restores_alphabet(self):
        texts = {'p':'abab','q':'abab'}
        nodes = {p:{'bodies':[],'prefix':[],'identifier':[]} for p in texts}
        initial = [c.literal('a'),c.literal('b')]
        state,info = s.optimize(texts,nodes,initial,[],['ab'],set(),{'trials':20,'seconds':5},False)
        self.assertTrue(set(initial) <= set(state['keys']))
        self.assertNotIn(c.literal('c'),state['keys'])
        self.assertLess(state['selections'],8)
        self.assertLessEqual(info['trials'],20)

    def test_nested_prefix_generated_byte_accounting(self):
        # Literal leaves can cover an expression in one paid code with zero
        # generated bytes, while the competing prefix shape generates '+'.
        text = 'function solve(a,b,c){return (a+b)+c}'
        nodes = c.extract({'p':text})['p']
        keys = c.order([c.literal(x) for x in c.ALPHABET]+[c.literal('a+b')]+[
            n['key'] for n in nodes['prefix'] if n['key']])
        plan = c.encode_source(text,nodes,keys)
        self.assertEqual(c.decode_many(keys,{'p':plan})['p'],text)
        self.assertEqual(plan['generated_bytes'],plan['prefix_fixed_bytes'])


if __name__ == '__main__':
    unittest.main()
