"""Model-generated paraphrases for recognition queries (labelled as such).

Paraphrases are generated by the same local model (Qwen3.5-4B, thinking off,
greedy) in batches, after the sample manifest is frozen. Each paraphrase is
checked for constraint preservation: every number in the original statement's
constraints section must still appear. Failing paraphrases are kept but
flagged, so the report can show results with and without them.
"""

from __future__ import annotations

import hashlib
import json
import re

from .lookup import _constraints_section
from .records import DERIVED
from .splits import IndexEntry

PARAPHRASES_PATH = DERIVED / "paraphrases.jsonl"
MAX_NEW_TOKENS = 1536
BATCH = 8

INSTRUCTION = (
    "Rewrite the following programming problem statement in your own words, as a different author would. "
    "Change sentence structure and wording, but keep the task, every number, every constraint, the meaning of each "
    "input and output, and all examples exactly equivalent. Do not solve the problem. Do not include code. "
    "Output only the rewritten statement.\n\n### Statement\n"
)

_NUMBER_RE = re.compile(r"\d+")


def numbers_preserved(original: str, paraphrase: str) -> float:
    wanted = set(_NUMBER_RE.findall(_constraints_section(original)))
    if not wanted:
        return 1.0
    have = set(_NUMBER_RE.findall(paraphrase))
    return len(wanted & have) / len(wanted)


def generate(generator, entries: list[IndexEntry]) -> dict[str, dict]:
    done: dict[str, dict] = {}
    if PARAPHRASES_PATH.exists():
        for line in PARAPHRASES_PATH.read_text(encoding="utf-8").splitlines():
            item = json.loads(line)
            done[item["key"]] = item
    todo = [e for e in entries if e.key not in done]
    with PARAPHRASES_PATH.open("a", encoding="utf-8") as out:
        for start in range(0, len(todo), BATCH):
            batch = todo[start:start + BATCH]
            prompts = [[{"role": "user", "content": INSTRUCTION + e.statement.strip()}] for e in batch]
            texts = generator.generate_batch(prompts, max_new_tokens=MAX_NEW_TOKENS)
            for entry, text in zip(batch, texts):
                text = text.strip()
                item = {
                    "key": entry.key,
                    "paraphrase": text,
                    "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
                    "numbers_preserved": round(numbers_preserved(entry.statement, text), 3),
                    "chars_original": len(entry.statement),
                    "chars_paraphrase": len(text),
                    "generator": "Qwen/Qwen3.5-4B@851bf6e8 greedy thinking-off batch",
                }
                done[entry.key] = item
                out.write(json.dumps(item, ensure_ascii=False) + "\n")
                out.flush()
            print(f"[paraphrase] {min(start + BATCH, len(todo))}/{len(todo)}", flush=True)
    return done


def query_text(entry: IndexEntry, paraphrase: str) -> str:
    """A user paste: paraphrased statement plus the unchanged starter code."""
    if entry.starter_code.strip():
        return f"{paraphrase.strip()}\n\n{entry.starter_code.rstrip()}\n"
    return paraphrase.strip() + "\n"
