import assert from 'node:assert/strict';
import { derive, correction } from './operator.mjs';
const a = new Float32Array([3,4]);
const h = new Float32Array([2,3,4]);
const ref = new Float32Array([1,2,3]);
const frozen = [...a,...h,...ref];
const op = derive(a,h,ref);
for (const x of correction(op,a)) assert.ok(Math.abs(x-0.25)<1e-6);
assert.deepEqual([...a,...h,...ref], frozen);
assert.deepEqual([...correction(derive(a,h,ref,0),a)], [0,0,0]);
assert.deepEqual([...correction(derive(new Float32Array(2),h,ref),a)], [0,0,0]);
for (const x of correction(derive(a,h,ref,-0.25),a)) assert.ok(Math.abs(x+0.25)<1e-6);
const large = derive(a,h,new Float32Array([1000,2000,3000]));
assert.ok(Math.hypot(...correction(large,a)) <= Math.hypot(...h)*0.250001);
assert.throws(()=>derive([NaN],h,ref));
assert.throws(()=>derive(a,h,[1]));
assert.throws(()=>derive(a,h,ref,2));
console.log('Rank-one target geometry, sign, identity, norm bound, immutability and invalid cases passed');
const { tasks } = await import('./tasks.mjs');
for (const [id, body, choices, answer] of tasks) assert.equal(String(Function(body)()), choices[answer], id);
assert.deepEqual([0,1,2,3].map(i=>tasks.filter(t=>t[3]===i).length), [2,2,2,2]);
console.log('Eight fresh code oracles and balanced labels verified');
