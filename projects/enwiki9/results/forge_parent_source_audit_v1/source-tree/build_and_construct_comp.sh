#!/bin/bash -x

SEED="${FX3_SEED:-${SEED:-923}}"
UPDATE_LIMIT="${FX3_UPDATE_LIMIT:-${UPDATE_LIMIT:-3000}}"
LSTM_CELLS="${FX3_LSTM_CELLS:-${LSTM_CELLS:-200}}"
LSTM_LAYERS="${FX3_LSTM_LAYERS:-${LSTM_LAYERS:-1}}"
LSTM_HORIZON="${FX3_LSTM_HORIZON:-${LSTM_HORIZON:-128}}"
LSTM_LR="${FX3_LSTM_LR:-${LSTM_LR:-0.03}}"
LSTM_LR_FINAL="${FX3_LSTM_LR_FINAL:-${LSTM_LR_FINAL:-0}}"
LSTM_LR_DECAY_START_BYTES="${FX3_LSTM_LR_DECAY_START_BYTES:-${LSTM_LR_DECAY_START_BYTES:-0}}"
LSTM_LR_DECAY_END_BYTES="${FX3_LSTM_LR_DECAY_END_BYTES:-${LSTM_LR_DECAY_END_BYTES:-0}}"
LSTM_CLIP="${FX3_LSTM_CLIP:-${LSTM_CLIP:-10}}"
BYTE_MIXER_INPUT_SCALE="${FX3_BYTE_MIXER_INPUT_SCALE:-${BYTE_MIXER_INPUT_SCALE:-2}}"
