LSTM_FXCM_MIN_ABS_STRETCH="${FX3_LSTM_FXCM_MIN_ABS_STRETCH:-${LSTM_FXCM_MIN_ABS_STRETCH:-0}}"
LSTM_EX_CONTEXT_DIVISOR="${FX3_LSTM_EX_CONTEXT_DIVISOR:-${LSTM_EX_CONTEXT_DIVISOR:-1}}"
LSTM_CONF_INPUT_SCALE="${FX3_LSTM_CONF_INPUT_SCALE:-${LSTM_CONF_INPUT_SCALE:-0}}"
LSTM_CONF_CONTEXT_BUCKETS="${FX3_LSTM_CONF_CONTEXT_BUCKETS:-${LSTM_CONF_CONTEXT_BUCKETS:-0}}"
LSTM_SIGN_CONTEXT_BUCKETS="${FX3_LSTM_SIGN_CONTEXT_BUCKETS:-${LSTM_SIGN_CONTEXT_BUCKETS:-0}}"
LSTMEX_BIT_HINT_SCALE="${FX3_LSTMEX_BIT_HINT_SCALE:-${LSTMEX_BIT_HINT_SCALE:-0}}"
LSTMEX_BIT_HINT_MIN_CONF="${FX3_LSTMEX_BIT_HINT_MIN_CONF:-${LSTMEX_BIT_HINT_MIN_CONF:-0}}"
LSTM_TRAIN_MIN_ACTUAL_PROB="${FX3_LSTM_TRAIN_MIN_ACTUAL_PROB:-${LSTM_TRAIN_MIN_ACTUAL_PROB:-0}}"
LSTM_TRAIN_MAX_ACTUAL_PROB="${FX3_LSTM_TRAIN_MAX_ACTUAL_PROB:-${LSTM_TRAIN_MAX_ACTUAL_PROB:-1}}"
LSTM_TRAIN_STRIDE="${FX3_LSTM_TRAIN_STRIDE:-${LSTM_TRAIN_STRIDE:-1}}"
LSTM_TRAIN_OFFSET="${FX3_LSTM_TRAIN_OFFSET:-${LSTM_TRAIN_OFFSET:-0}}"
LSTM_LOWPROB_INPUT_THRESHOLD="${FX3_LSTM_LOWPROB_INPUT_THRESHOLD:-${LSTM_LOWPROB_INPUT_THRESHOLD:-0}}"
LSTM_LOWPROB_INPUT_SCALE="${FX3_LSTM_LOWPROB_INPUT_SCALE:-${LSTM_LOWPROB_INPUT_SCALE:-1}}"
LSTM_LOWPROB_CONTEXT_THRESHOLD="${FX3_LSTM_LOWPROB_CONTEXT_THRESHOLD:-${LSTM_LOWPROB_CONTEXT_THRESHOLD:-0}}"
LSTM_LOWPROB_CONTEXT_BUCKETS="${FX3_LSTM_LOWPROB_CONTEXT_BUCKETS:-${LSTM_LOWPROB_CONTEXT_BUCKETS:-0}}"
LSTM_LOWPROB_CONTEXT_LR="${FX3_LSTM_LOWPROB_CONTEXT_LR:-${LSTM_LOWPROB_CONTEXT_LR:-0.001}}"
LSTM_MIXER_CONTEXT_BUCKETS="${FX3_LSTM_MIXER_CONTEXT_BUCKETS:-${LSTM_MIXER_CONTEXT_BUCKETS:-0}}"
LSTM_MIXER_CONTEXT_LR="${FX3_LSTM_MIXER_CONTEXT_LR:-${LSTM_MIXER_CONTEXT_LR:-0.0005}}"
AUX_CONTEXT_MODE="${FX3_AUX_CONTEXT_MODE:-${AUX_CONTEXT_MODE:-0}}"
AUX_DISAGREE_BUCKETS="${FX3_AUX_DISAGREE_BUCKETS:-${AUX_DISAGREE_BUCKETS:-8}}"
LAYER1_LR="${FX3_LAYER1_LR:-${LAYER1_LR:-0.0003}}"
LAYER1_FXCM_INPUT_SCALE="${FX3_LAYER1_FXCM_INPUT_SCALE:-${LAYER1_FXCM_INPUT_SCALE:-1}}"
LAYER1_BYTE_MIXER_INPUT_SCALE="${FX3_LAYER1_BYTE_MIXER_INPUT_SCALE:-${LAYER1_BYTE_MIXER_INPUT_SCALE:-1}}"
LAYER1_LSTM_CONTEXT_BUCKETS="${FX3_LAYER1_LSTM_CONTEXT_BUCKETS:-${LAYER1_LSTM_CONTEXT_BUCKETS:-0}}"
LSTM_INPUT_UNIFORM_BLEND="${FX3_LSTM_INPUT_UNIFORM_BLEND:-${LSTM_INPUT_UNIFORM_BLEND:-0}}"
LSTM_INPUT_CENTER_SCALE="${FX3_LSTM_INPUT_CENTER_SCALE:-${LSTM_INPUT_CENTER_SCALE:-1}}"
LSTM_ADAM_CACHE_LIMIT_CONSTANTS="${FX3_LSTM_ADAM_CACHE_LIMIT_CONSTANTS:-${LSTM_ADAM_CACHE_LIMIT_CONSTANTS:-0}}"
MIXER_CONTEXT64="${FX3_MIXER_CONTEXT64:-${MIXER_CONTEXT64:-0}}"
MIXER_CONTEXT_LIMIT="${FX3_MIXER_CONTEXT_LIMIT:-${MIXER_CONTEXT_LIMIT:-10000}}"
VERB_WORDS1_LIMIT="${FX3_VERB_WORDS1_LIMIT:-${VERB_WORDS1_LIMIT:-451531986}}"
INITIAL_BLPOS="${FX3_INITIAL_BLPOS:-${INITIAL_BLPOS:-0}}"
WORD_ORDER_SKIP_LIMIT="${FX3_WORD_ORDER_SKIP_LIMIT:-${WORD_ORDER_SKIP_LIMIT:-463139793}}"
DECCODE_LASTCW_LIMIT="${FX3_DECCODE_LASTCW_LIMIT:-${DECCODE_LASTCW_LIMIT:-448131719}}"
UPX_MODE="${FX3_UPX_MODE:-${UPX_MODE:-9}}"

case "$UPX_MODE" in
  9|-9|default)
    UPX_ARGS=(-9)
    ;;
  best)
    UPX_ARGS=(--best)
    ;;
  best_lzma|lzma)
    UPX_ARGS=(--best --lzma)
    ;;
  brute)
    UPX_ARGS=(--brute)
    ;;
  ultra_brute)
    UPX_ARGS=(--ultra-brute)
    ;;
  *)
    printf 'unsupported FX3_UPX_MODE: %s\n' "$UPX_MODE" >&2
    exit 2
    ;;
esac

rm -rf pgo_data
mkdir -p pgo_data

# building with PGO
CFLAGS_DEFINES="-DSEED=$SEED -DUPDATE_LIMIT=$UPDATE_LIMIT -DFX3_LSTM_CELLS=$LSTM_CELLS -DFX3_LSTM_LAYERS=$LSTM_LAYERS -DFX3_LSTM_HORIZON=$LSTM_HORIZON -DFX3_LSTM_LR=$LSTM_LR -DFX3_LSTM_LR_FINAL=$LSTM_LR_FINAL -DFX3_LSTM_LR_DECAY_START_BYTES=$LSTM_LR_DECAY_START_BYTES -DFX3_LSTM_LR_DECAY_END_BYTES=$LSTM_LR_DECAY_END_BYTES -DFX3_LSTM_CLIP=$LSTM_CLIP -DFX3_BYTE_MIXER_INPUT_SCALE=$BYTE_MIXER_INPUT_SCALE -DFX3_BYTE_MIXER_OUTPUT_EPS=$BYTE_MIXER_OUTPUT_EPS -DFX3_BYTE_MIXER_EXACT_OVERRIDE=$BYTE_MIXER_EXACT_OVERRIDE -DFX3_LSTM_FXCM_INPUT_SCALE=$LSTM_FXCM_INPUT_SCALE -DFX3_LSTM_FXCM_MIN_ABS_STRETCH=$LSTM_FXCM_MIN_ABS_STRETCH -DFX3_LSTM_EX_CONTEXT_DIVISOR=$LSTM_EX_CONTEXT_DIVISOR -DFX3_LSTM_CONF_INPUT_SCALE=$LSTM_CONF_INPUT_SCALE -DFX3_LSTM_CONF_CONTEXT_BUCKETS=$LSTM_CONF_CONTEXT_BUCKETS -DFX3_LSTM_SIGN_CONTEXT_BUCKETS=$LSTM_SIGN_CONTEXT_BUCKETS -DFX3_LSTMEX_BIT_HINT_SCALE=$LSTMEX_BIT_HINT_SCALE -DFX3_LSTMEX_BIT_HINT_MIN_CONF=$LSTMEX_BIT_HINT_MIN_CONF -DFX3_LSTM_TRAIN_MIN_ACTUAL_PROB=$LSTM_TRAIN_MIN_ACTUAL_PROB -DFX3_LSTM_TRAIN_MAX_ACTUAL_PROB=$LSTM_TRAIN_MAX_ACTUAL_PROB -DFX3_LSTM_TRAIN_STRIDE=$LSTM_TRAIN_STRIDE -DFX3_LSTM_TRAIN_OFFSET=$LSTM_TRAIN_OFFSET -DFX3_LSTM_LOWPROB_INPUT_THRESHOLD=$LSTM_LOWPROB_INPUT_THRESHOLD -DFX3_LSTM_LOWPROB_INPUT_SCALE=$LSTM_LOWPROB_INPUT_SCALE -DFX3_LSTM_LOWPROB_CONTEXT_THRESHOLD=$LSTM_LOWPROB_CONTEXT_THRESHOLD -DFX3_LSTM_LOWPROB_CONTEXT_BUCKETS=$LSTM_LOWPROB_CONTEXT_BUCKETS -DFX3_LSTM_LOWPROB_CONTEXT_LR=$LSTM_LOWPROB_CONTEXT_LR -DFX3_LSTM_MIXER_CONTEXT_BUCKETS=$LSTM_MIXER_CONTEXT_BUCKETS -DFX3_LSTM_MIXER_CONTEXT_LR=$LSTM_MIXER_CONTEXT_LR -DFX3_AUX_CONTEXT_MODE=$AUX_CONTEXT_MODE -DFX3_AUX_DISAGREE_BUCKETS=$AUX_DISAGREE_BUCKETS -DFX3_LAYER1_LR=$LAYER1_LR -DFX3_LAYER1_FXCM_INPUT_SCALE=$LAYER1_FXCM_INPUT_SCALE -DFX3_LAYER1_BYTE_MIXER_INPUT_SCALE=$LAYER1_BYTE_MIXER_INPUT_SCALE -DFX3_LAYER1_LSTM_CONTEXT_BUCKETS=$LAYER1_LSTM_CONTEXT_BUCKETS -DFX3_LSTM_INPUT_UNIFORM_BLEND=$LSTM_INPUT_UNIFORM_BLEND -DFX3_LSTM_INPUT_CENTER_SCALE=$LSTM_INPUT_CENTER_SCALE -DFX3_LSTM_ADAM_CACHE_LIMIT_CONSTANTS=$LSTM_ADAM_CACHE_LIMIT_CONSTANTS -DFX3_MIXER_CONTEXT64=$MIXER_CONTEXT64 -DFX3_MIXER_CONTEXT_LIMIT=$MIXER_CONTEXT_LIMIT -DFX3_VERB_WORDS1_LIMIT=$VERB_WORDS1_LIMIT -DFX3_INITIAL_BLPOS=$INITIAL_BLPOS -DFX3_WORD_ORDER_SKIP_LIMIT=$WORD_ORDER_SKIP_LIMIT -DFX3_DECCODE_LASTCW_LIMIT=$DECCODE_LASTCW_LIMIT"
if [[ -n "${EXTRA_CFLAGS_DEFINES:-}" ]]; then
  CFLAGS_DEFINES="$CFLAGS_DEFINES $EXTRA_CFLAGS_DEFINES"
fi
if [[ -n "${FX3_FINAL_CFLAGS_DEFINES:-}" ]]; then
  CFLAGS_DEFINES="$CFLAGS_DEFINES $FX3_FINAL_CFLAGS_DEFINES"
fi
make CFLAGS_DEFINES="$CFLAGS_DEFINES" prof_gen -j

./cmix -c ./prof_input/input ./prof_comp > ./prof_output
rm ./prof_comp ./prof_output
llvm-profdata-17 merge -output=default.profdata ./pgo_data/*
mv default.profdata pgo_data/

make CFLAGS_DEFINES="$CFLAGS_DEFINES" prof_use -j
cp ./cmix ./cmix.before_upx
upx-ucl "${UPX_ARGS[@]}" cmix

# this is a directory where the compressor binary will be placed
DIR=run
mkdir -p ./$DIR
ROOT=$(pwd)
cp ./cmix.before_upx $DIR/cmix_before_upx
cp ./cmix $DIR/cmix_orig
# git diff > $DIR/patch
# exit
# building a selfextracting binary
pushd $DIR
# creating a compressed version of dictionary
./cmix_orig -c $ROOT/dictionary/english.dic ./comp_dict
# creating a compressed verions of a file with new order
./cmix_orig -c $ROOT/src/readalike_prepr/data/new_article_order ./comp_order
# creating a header with size of the above files
./cmix_orig -h $(wc -c ./comp_dict | awk '{print $1}') $(wc -c ./comp_order | awk '{print $1}') 0

# merging the above files and setting permissions for the final executable file
cat ./cmix_orig ./comp_dict ./comp_order header.dat > ./cmix
chmod +x ./cmix
