import assert from 'node:assert/strict';
import { serialize, reconstruct, transform, estimate } from './operator.mjs';
import { counter, evaluate, probes, propose, tasks } from './experiment.mjs';
const phi = [-0.8, -0, 0, 0.4];
assert.deepEqual(reconstruct(serialize(phi)), phi);
const population = tasks(87, 4), budget = counter();
const p = propose(phi, phi, 'hereditary', population, 2, 42, budget);
assert.deepEqual(phi, [-0.8, -0, 0, 0.4]);
assert.equal(budget.metaObjectiveCalls, 8);
assert.equal(budget.scalarLossCalls, 8 * 4 * (2 * 8 + 1));
assert.equal(budget.transforms, 8 * 4 * 2 + 1);
assert.deepEqual(p, propose(phi, phi, 'fixed_proposer', population, 2, 42, counter()));
assert.deepEqual(phi, propose(phi, phi, 'serialization_only', population, 2, 42, counter()));
const e = { directions: [[1, 1], [1, -1], [-1, 1], [-1, -1]], radius: 0.001 };
const x = [0.2, -0.3], f = v => v[0] ** 2 + 2 * v[1] ** 2;
e.plus = e.directions.map(d => f(x.map((v,i) => v + e.radius*d[i])));
e.minus = e.directions.map(d => f(x.map((v,i) => v - e.radius*d[i])));
const g = estimate(x,e);
assert.ok(Math.abs(g[0] - 0.4) < 1e-10 && Math.abs(g[1] + 1.2) < 1e-10);
assert.throws(() => transform(phi, x, { ...e, plus: [NaN, 0, 0, 0] }));
assert.deepEqual(evaluate(p,population,2,counter()),evaluate(reconstruct(serialize(p)),population,2,counter()));
assert.deepEqual(probes(x,f,71),probes(x,f,71));
console.log('Scalar-probe reconstruction, closure, isolation, budgets and oracle checks passed');
